/**
 * Контракт домену «Каталог» (`docs/backend/frontend-seam.md`): розклад, пояси, країни, міста, події, традиції.
 * Статика: змінюється з адмінки рідко й не під час свята, тож лишається синхронною і вбудовується під час збирання
 * (`lib/data/load.getData()`); оновлення — перезбирання (чи ISR, якщо відмовимось від статичного експорту — див. ADR).
 * Чого в каталозі НЕМАЄ: ланцюжків трансляцій і їхніх статусів — це домен `live` (змінюється щохвилини в ніч свята).
 */
import type { Dataset } from '@/lib/data/types';

/** Каталог = набір даних без ланцюжків трансляцій. */
export type Catalog = Omit<Dataset, 'chainsByEventId'>;

export interface CatalogService {
  /** Синхронно, з пакета збирання. Майбутнє джерело — Payload під час збирання (`GET /api/catalog` → JSON). */
  catalog(): Catalog;
  /** Версія даних збірки (`meta.generatedAt` + `tzdbVersion`) — для журналу й перевірки, що CDN віддає свіже. */
  version(): string;
}
